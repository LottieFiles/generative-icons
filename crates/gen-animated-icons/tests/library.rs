#[test]
fn a_bad_catalog_is_an_integrity_error() {
    let dir = tempfile::tempdir().unwrap();
    let library = dir.path().join("library");
    write(&library, "catalog.json", r#"{"schemaVersion":1,"version":"1","icons":[{"id":"../x","label":"X"}]}"#);
    let error = run(dir.path(), &["search", "x", "--library", library.to_str().unwrap()]).fails(6, "INVALID_CATALOG");
    assert!(error["message"].as_str().unwrap().ends_with("an icon has an invalid id"), "{error}");
    run(dir.path(), &["search", "x", "--library", "no-such-folder"]).fails(6, "INVALID_CATALOG");
}

/// Search over the whole released catalog: common synonyms find the icon, and weak
/// matches no longer pad the results.
#[test]
fn search_uses_synonyms_and_a_relevance_floor() {
    let dist = require!(packages_dist(), "packages/icons/dist");
    let library = dist.to_str().unwrap();
    let dir = tempfile::tempdir().unwrap();
    let search = |query: &str| -> Vec<String> {
        let results = run(dir.path(), &["search", query, "--limit", "40", "--library", library]).ok();
        ids(&results).into_iter().map(String::from).collect()
    };
    let delete = search("delete");
    let mut named = delete[..2].to_vec();
    named.sort();
    assert_eq!(named, ["delete-message", "photo-delete"], "{delete:?}");
    assert!(delete.contains(&"trash".to_string()), "{delete:?}");
    let remove = search("remove");
    assert!(!remove.contains(&"agent-checkpoint".to_string()) && remove.contains(&"trash".to_string()), "{remove:?}");
    assert!(search("plant grow").is_empty());
    assert!(search("envelope").contains(&"mail".to_string()));
    // Ranked as before where the query names the icon.
    assert_eq!(search("notification bell")[..3], ["bell", "notification-settings", "bell-off"]);
}
