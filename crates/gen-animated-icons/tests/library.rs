//! Library sources and search: local folders, HTTP with caching, and offline use.

mod common;

use common::*;
use serde_json::{Value, json};

fn ids(results: &Value) -> Vec<&str> {
    results.as_array().unwrap().iter().map(|r| r["id"].as_str().unwrap()).collect()
}

#[test]
fn ranked_and_all_words_search() {
    let dir = tempfile::tempdir().unwrap();
    let library = fixture_library(&dir.path().join("library"));
    let library = library.to_str().unwrap();

    let results = run(dir.path(), &["search", "notification", "--library", library]).ok();
    assert_eq!(
        results,
        json!([{"id": "bell-ring", "label": "Bell ring", "category": "Notifications", "stateful": false,
                "origin": "library", "set": "99-fixture", "score": 6, "matchedTerms": ["notifications", "bell"]}])
    );
    // An icon named by the query comes first, although bell-ring also scores the
    // Notifications category through the bell alias group (16 against 15): its score is
    // raised past the rest, so ordering by score keeps it first.
    let renamed = dir.path().join("renamed");
    fixture_library(&renamed);
    let catalog = read(&renamed, "catalog.json")
        .replace("\"id\": \"menu\"", "\"id\": \"bell\"")
        .replace("\"label\": \"Menu\"", "\"label\": \"Bell\"");
    write(&renamed, "catalog.json", catalog);
    let renamed = renamed.to_str().unwrap();
    let results = run(dir.path(), &["search", "bell", "--library", renamed]).ok();
    let scores: Vec<(&str, u64)> =
        results.as_array().unwrap().iter().map(|r| (r["id"].as_str().unwrap(), r["score"].as_u64().unwrap())).collect();
    assert_eq!(scores, [("bell", 17), ("bell-ring", 16)]);
    assert_eq!(ids(&run(dir.path(), &["search", "Bell", "--limit", "1", "--library", renamed]).ok()), ["bell"]);
    let results = run(dir.path(), &["search", "the", "range", "--library", library]).ok();
    assert_eq!(ids(&results), ["date-range"]);
    assert_eq!(results[0]["score"], 15);

    let results = run(dir.path(), &["search", "--match", "all-words", "BE", "--library", library]).ok();
    assert_eq!(ids(&results), ["heart", "bell-ring"]);
    assert!(results[0].get("score").is_none());
    let all = run(dir.path(), &["search", "--match", "all-words", "--library", library]).ok();
    assert_eq!(ids(&all), ["heart", "bell-ring", "menu", "date-range"]);
    let limited = run(dir.path(), &["search", "--match", "all-words", "--limit", "1", "--library", library]).ok();
    assert_eq!(ids(&limited), ["heart"]);

    let text = run(dir.path(), &["search", "zzzz", "--format", "text", "--library", library]);
    assert_eq!(text.stdout, "No icons match \"zzzz\". Try a synonym or the underlying object.\n");
}

#[test]
fn search_includes_the_projects_local_icons() {
    let dir = tempfile::tempdir().unwrap();
    let app = &dir.path().join("app");
    std::fs::create_dir(app).unwrap();
    web_app(app);
    let library = fixture_library(&dir.path().join("library"));
    let library = library.to_str().unwrap();
    run(app, &["init"]).ok();
    // What `build` records for a local icon. Its label names the query: search drops a
    // match only in the description when another icon is named for it.
    write(
        app,
        "src/gen-animated-icons/rocket-launch.mjs",
        "// Generated by gen-animated-icons. Review local edits before updating.\nexport const icon = {\n  \"id\": \"rocket-launch\",\n  \"label\": \"Heart rocket\",\n  \"intent\": \"A rocket lifts off with a heart-shaped flame.\",\n  \"stateful\": true\n};\nexport const src = \"/gen-animated-icons/rocket-launch.lottie\";\nexport default icon;\n",
    );
    let lock_file = app.join(".gen-animated-icons/lock.json");
    let mut lock: Value = serde_json::from_str(&std::fs::read_to_string(&lock_file).unwrap()).unwrap();
    lock["icons"]["rocket-launch"] = json!({"version": "local", "origin": "local", "sha256": "0",
        "source": "src/gen-animated-icons/rocket-launch.mjs", "asset": "public/gen-animated-icons/rocket-launch.lottie"});
    std::fs::write(&lock_file, gai_core::to_js_json_pretty(&lock, 2) + "\n").unwrap();

    let results = run(app, &["search", "heart", "--library", library]).ok();
    assert_eq!(ids(&results), ["heart", "rocket-launch"]);
    assert_eq!(results[1]["origin"], "local");
    assert_eq!(results[1]["stateful"], true);
    let local = run(app, &["search", "heart", "--local-only"]).ok();
    assert_eq!(ids(&local), ["rocket-launch"]);
    assert_eq!(ids(&run(app, &["search", "heart", "--library-only", "--library", library]).ok()), ["heart"]);
    assert_eq!(run(app, &["info", "--library", library]).ok()["localIcons"], json!(["rocket-launch"]));
    run(dir.path(), &["search", "heart", "--local-only"]).fails(3, "PROJECT_NOT_FOUND");
}

#[test]
fn http_library_is_verified_cached_and_usable_offline() {
    let dir = tempfile::tempdir().unwrap();
    let served = dir.path().join("served/library/v1");
    fixture_library(&served);
    let base = serve(dir.path().join("served"));
    let url = format!("{base}library/v1/");
    let app = &dir.path().join("app");
    std::fs::create_dir(app).unwrap();
    web_app(app);
    run(app, &["init"]).ok();

    let cache = dir.path().join("cache");
    let cache_env = [("GEN_ANIMATED_ICONS_CACHE_DIR", cache.to_str().unwrap())];
    let result = run_with(app, &["add", "heart", "--library", &url], &cache_env).ok();
    assert_eq!(result["version"], FIXTURE_VERSION);
    let asset = std::fs::read(app.join("public/gen-animated-icons/heart.lottie")).unwrap();
    let digest = gai_core::sha256_hex(&asset);
    assert_eq!(std::fs::read(cache.join(format!("assets/{digest}.lottie"))).unwrap(), asset);
    let catalogs: Vec<_> = std::fs::read_dir(cache.join("catalog")).unwrap().flatten().collect();
    assert_eq!(catalogs.len(), 1, "one folder per library URL");
    assert!(catalogs[0].path().join(format!("{FIXTURE_VERSION}.json")).is_file());

    // The environment variable selects the library too; --offline reuses the cache.
    let offline_app = &dir.path().join("offline-app");
    std::fs::create_dir(offline_app).unwrap();
    web_app(offline_app);
    run(offline_app, &["init"]).ok();
    let env = [cache_env[0], ("GEN_ANIMATED_ICONS_LIBRARY", url.as_str())];
    run_with(offline_app, &["add", "heart", "--offline"], &env).ok();
    let error = run_with(offline_app, &["add", "menu", "--offline"], &env).fails(5, "NETWORK");
    assert_eq!(error["id"], "menu");
    let results = run_with(offline_app, &["search", "bell", "--offline"], &env).ok();
    assert_eq!(ids(&results), ["bell-ring"]);

    // A served file that does not match the catalog is refused and never cached.
    std::fs::write(served.join("assets/menu.lottie"), b"tampered").unwrap();
    let error = run_with(app, &["add", "menu", "--library", &url], &cache_env).fails(6, "HASH_MISMATCH");
    assert_eq!(error["message"], "Package asset hash mismatch: menu");
    assert!(!app.join("public/gen-animated-icons/menu.lottie").exists());
    assert_eq!(std::fs::read_dir(cache.join("assets")).unwrap().count(), 1);

    let missing = format!("{base}nowhere/");
    let error = run_with(app, &["search", "bell", "--library", &missing], &cache_env).fails(5, "NETWORK");
    assert!(error["message"].as_str().unwrap().starts_with("No library catalog at "), "{error}");

    // Plain http is for local servers only.
    let error =
        run_with(app, &["search", "bell", "--library", "http://example.com/library/v1/"], &cache_env).fails(2, "USAGE");
    assert_eq!(error["message"], "The library URL must use https: http://example.com/library/v1/");
}

#[test]
fn default_library_offline_without_cache_fails_cleanly() {
    let dir = tempfile::tempdir().unwrap();
    let error = run(dir.path(), &["search", "bell", "--offline"]).fails(5, "NETWORK");
    assert_eq!(error["message"], "Offline, and the library catalog is not cached");
    let info = run(dir.path(), &["info", "--offline"]);
    assert_eq!(info.code, 0, "{info:?}");
    assert_eq!(info.json()["libraryVersion"], Value::Null);
    assert!(info.stderr.contains("Library unavailable"), "{}", info.stderr);
}

