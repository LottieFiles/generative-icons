/// Our ranked results in the shape `generation-context.mjs --search` prints.
fn as_generation_context(results: &Value) -> String {
    let projected: Vec<Value> = results
        .as_array()
        .unwrap()
        .iter()
        .map(|r| json!({"id": r["id"], "label": r["label"], "category": r["category"], "score": r["score"], "matchedTerms": r["matchedTerms"]}))
        .collect();
    gai_core::to_js_json_pretty(&Value::Array(projected), 2) + "\n"
}

#[test]
fn ranked_search_matches_generation_context() {
    require!(packages_dist(), "packages/icons/dist");
    let repo = repo_root();
    let dir = tempfile::tempdir().unwrap();
    let library = repo.to_str().unwrap();
    let ids = |results: &Value| -> Vec<String> {
        results.as_array().unwrap().iter().map(|r| r["id"].as_str().unwrap().to_string()).collect()
    };
    for (query, golden) in SEARCHES {
        // `context --search` is the port of `generation-context.mjs --search`.
        let results = run(dir.path(), &["context", query, "--search", "--limit", "6", "--library", library]).ok();
        assert_eq!(gai_core::sha256_hex(as_generation_context(&results)), golden, "{query}");
        // `search` ranks the same way, except that icons the query names come first, and
        // that it adds synonyms and leaves out padding: icons matching only in their
        // description beside icons named for the query, or matching only some words.
        let searched = run(dir.path(), &["search", query, "--limit", "6", "--library", library]).ok();
        let (ranked, shown) = (ids(&results), ids(&searched));
        match query {
            "notification bell" => {}
            "package return" => {
                assert_eq!(shown[..3], ranked[..3], "{query}");
                // A description-only "return" (air-conditioner, announcement) gives way to
                // icons of the delivery category, which the query's "package" names.
                assert_eq!(shown[3..], ["inventory", "pickup-locker", "subscription-box"], "{query}");
            }
            // Two keyframe icons matched only the stray token "i" in their descriptions.
            "Café İstanbul key" => assert_eq!(shown, ranked[..4], "{query}"),
            _ => assert_eq!(gai_core::sha256_hex(as_generation_context(&searched)), golden, "{query}"),
        }
    }
    let searched = run(dir.path(), &["search", "notification bell", "--limit", "3", "--library", library]).ok();
    let ids: Vec<&str> = searched.as_array().unwrap().iter().map(|r| r["id"].as_str().unwrap()).collect();
    assert_eq!(ids, ["bell", "notification-settings", "bell-off"]);
    // Its score is raised to match, so ordering by score keeps it first.
    let scores: Vec<u64> = searched.as_array().unwrap().iter().map(|r| r["score"].as_u64().unwrap()).collect();
    assert!(scores.windows(2).all(|pair| pair[0] > pair[1]), "{scores:?}");
}

