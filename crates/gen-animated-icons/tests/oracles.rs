fn node() -> Option<()> {
    Command::new("node").arg("--version").output().ok().filter(|o| o.status.success()).map(drop)
}

/// Runs an ES module script with `input` on stdin and returns stdout.
fn node_script(script: &str, input: &str) -> String {
    let mut child = Command::new("node")
        .args(["--input-type=module", "-e", script])
        .current_dir(repo_root())
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    use std::io::Write;
    child.stdin.take().unwrap().write_all(input.as_bytes()).unwrap();
    let output = child.wait_with_output().unwrap();
    assert!(output.status.success(), "node failed");
    String::from_utf8(output.stdout).unwrap()
}

fn catalog(dist: &Path) -> Catalog {
    Catalog::parse(&std::fs::read(dist.join("catalog.json")).unwrap(), "catalog.json").unwrap()
}

#[test]
#[ignore = "whole catalog; needs node"]
fn every_label_ranks_like_generation_context() {
    let dist = require!(packages_dist(), "packages/icons/dist");
    require!(node(), "node");
    let repo = repo_root();
    let catalog = catalog(&dist);
    let index = SearchIndex::from_checkout(&repo).unwrap();
    // Each label and each intent's first three words, as a user might type them.
    let mut queries: Vec<String> = catalog.icons.iter().map(|icon| icon.label.clone()).collect();
    queries.extend(
        catalog
            .icons
            .iter()
            .filter_map(|i| i.intent.as_ref())
            .map(|i| i.split(' ').take(3).collect::<Vec<_>>().join(" ")),
    );
    let script = format!(
        "import fs from 'node:fs';\nimport {{ loadCatalog, searchIcons }} from '{}/motion/icon-sets/library/generation-context.mjs';\nconst {{ icons }} = loadCatalog('{}/');\nconst queries = JSON.parse(fs.readFileSync(0, 'utf8'));\nprocess.stdout.write(JSON.stringify(queries.map(q => searchIcons(icons, q, 20))));",
        repo.display(),
        repo.display()
    );
    let expected: Value =
        serde_json::from_str(&node_script(&script, &serde_json::to_string(&queries).unwrap())).unwrap();
    let searchables: Vec<Searchable<'_>> = catalog
        .icons
        .iter()
        .map(|icon| Searchable {
            id: &icon.id,
            label: &icon.label,
            category: icon.category.as_deref(),
            intent: icon.intent.as_deref(),
            brief: index.brief(&icon.id),
            aliases: &icon.aliases,
        })
        .collect();
    for (query, expected) in queries.iter().zip(expected.as_array().unwrap()) {
        let ours: Vec<Value> = ranked(&searchables, query, 20)
            .into_iter()
            .map(|hit| {
                let icon = &catalog.icons[hit.index];
                json!({"id": icon.id, "label": icon.label, "category": icon.category, "score": hit.score, "matchedTerms": hit.matched_terms})
            })
            .collect();
        assert_eq!(gai_core::to_js_json(&Value::Array(ours)), gai_core::to_js_json(expected), "{query}");
    }
    eprintln!("{} queries ranked identically", queries.len());
}

#[test]
#[ignore = "whole catalog; needs node"]
fn every_icon_bakes_like_the_runtime_bridge() {
    let dist = require!(packages_dist(), "packages/icons/dist");
    require!(node(), "node");
    let catalog = catalog(&dist);
    let weights = [1.0, 1.75, 2.3, 3.0];
    let script = format!(
        "import fs from 'node:fs';\nimport crypto from 'node:crypto';\nimport {{ rewriteStrokeWidth }} from '{}/packages/runtime/src/weight.mjs';\nconst {{ dist, ids, weights }} = JSON.parse(fs.readFileSync(0, 'utf8'));\nconst out = [];\nfor (const id of ids) {{ const bytes = fs.readFileSync(`${{dist}}/assets/${{id}}.lottie`); for (const w of weights) out.push(crypto.createHash('sha256').update(new Uint8Array(await rewriteStrokeWidth(bytes, w))).digest('hex')); }}\nprocess.stdout.write(JSON.stringify(out));",
        repo_root().display()
    );
    let ids: Vec<&str> = catalog.icons.iter().map(|icon| icon.id.as_str()).collect();
    let input = json!({"dist": dist, "ids": ids, "weights": weights});
    let expected: Vec<String> = serde_json::from_str(&node_script(&script, &input.to_string())).unwrap();
    let mut index = 0;
    for icon in &catalog.icons {
        let asset = std::fs::read(dist.join(&icon.asset_path)).unwrap();
        for weight in weights {
            let ours = gai_core::sha256_hex(rewrite_stroke_width(&asset, weight).unwrap());
            assert_eq!(ours, expected[index], "{} at {weight}", icon.id);
            index += 1;
        }
    }
    eprintln!("{index} baked assets identical");
}

#[test]
#[ignore = "whole catalog"]
fn every_icon_installs_on_web_and_android() {
    let dist = require!(packages_dist(), "packages/icons/dist");
    let library = dist.to_str().unwrap();
    let catalog = catalog(&dist);
    let ids: Vec<&str> = catalog.icons.iter().map(|icon| icon.id.as_str()).collect();
    let dir = tempfile::tempdir().unwrap();
    let web = &dir.path().join("web");
    let android = &dir.path().join("android");
    std::fs::create_dir_all(web).unwrap();
    std::fs::create_dir_all(android).unwrap();
    web_app(web);
    android_app(android);
    for app in [web, android] {
        run(app, &["init"]).ok();
        let mut args = vec!["add"];
        args.extend(&ids);
        args.extend(["--library", library]);
        let result = run(app, &args).ok();
        assert_eq!(result["icons"].as_array().unwrap().len(), ids.len());
    }
    for icon in &catalog.icons {
        let id = &icon.id;
        assert_eq!(sha(web, &format!("public/gen-animated-icons/{id}.lottie")), icon.asset_sha256);
        assert_eq!(sha(android, &format!("app/src/main/assets/{id}.lottie")), icon.asset_sha256);
        let module =
            gen_animated_icons::descriptor::read_installed(web, &format!("src/gen-animated-icons/{id}.mjs")).unwrap();
        assert_eq!(gai_core::to_js_json(&module), gai_core::to_js_json(&icon.descriptor), "{id}");
        assert_eq!(
            read(android, &format!("gen-animated-icons/descriptors/{id}.json")),
            gai_core::to_js_json_pretty(&icon.descriptor, 2) + "\n"
        );
    }
    for app in [web, android] {
        let diff = run(app, &["diff"]).ok();
        assert!(diff.as_array().unwrap().iter().all(|s| s["status"] == "unchanged"));
        let mut args = vec!["remove"];
        args.extend(&ids);
        run(app, &args).ok();
        let lock: Value = serde_json::from_str(&read(app, ".gen-animated-icons/lock.json")).unwrap();
        assert_eq!(lock["icons"], json!({}));
    }
    eprintln!("{} icons installed and removed on web and Android", ids.len());
}
