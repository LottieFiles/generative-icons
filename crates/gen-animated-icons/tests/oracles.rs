    run(app, &["init"]).ok();
    for (id, weight, golden, _) in BAKED {
        let weight = weight.to_string();
        run(app, &["add", id, "--bake-weight", &weight, "--library", dist.to_str().unwrap()]).ok();
        assert_eq!(sha(app, &format!("app/src/main/assets/{id}.lottie")), golden, "{id} at {weight}");
    }
