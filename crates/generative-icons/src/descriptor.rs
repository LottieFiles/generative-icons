//! Installed descriptors: generated web modules and native JSON files.

use crate::error::{CliError, ErrorCode, Result};
use crate::managed::{inside, read_optional};
use serde_json::Value;
use std::path::Path;

/// Text before the descriptor JSON in a generated web module.
const ICON_PREFIX: &str = "export const icon = ";
/// Text right after it.
const ICON_SUFFIX: &str = ";\nexport const src = ";

/// Reads the descriptor installed at the project-relative `source`: a generated
/// `.mjs` module (the JSON between `export const icon = ` and `;\nexport const src = `)
/// or a `.json` file.
pub fn read_installed(root: &Path, source: &str) -> Result<Value> {
    let file = inside(root, source)?;
    let not_generated = |detail: &str| {
        CliError::new(ErrorCode::InvalidConfig, format!("{source} is not a generated descriptor: {detail}"))
            .with_path(source)
    };
    let bytes = read_optional(&file)?.ok_or_else(|| not_generated("missing"))?;
    let text = String::from_utf8(bytes).map_err(|_| not_generated("not UTF-8"))?;
    let json = if source.ends_with(".mjs") {
        let start = text.find(ICON_PREFIX).ok_or_else(|| not_generated("no icon export"))? + ICON_PREFIX.len();
        let end = text[start..].find(ICON_SUFFIX).ok_or_else(|| not_generated("no src export"))? + start;
        &text[start..end]
    } else {
        &text
    };
    serde_json::from_str(json).map_err(|error| not_generated(&error.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_web_and_native_descriptors() {
        let dir = tempfile::tempdir().unwrap();
        let module = "// Generated by generative-icons.\nexport const icon = {\n  \"id\": \"x\"\n};\nexport const src = \"/x.lottie\";\nexport default icon;\n";
        std::fs::write(dir.path().join("x.mjs"), module).unwrap();
        std::fs::write(dir.path().join("x.json"), "{\"id\":\"x\"}\n").unwrap();
        assert_eq!(read_installed(dir.path(), "x.mjs").unwrap()["id"], "x");
        assert_eq!(read_installed(dir.path(), "x.json").unwrap()["id"], "x");
        std::fs::write(dir.path().join("y.mjs"), "export default {};\n").unwrap();
        assert_eq!(read_installed(dir.path(), "y.mjs").unwrap_err().code, ErrorCode::InvalidConfig);
    }
}
