#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { digest, inside, inspectProject, json, read, readConfig, writeBatch } from './project.mjs';

const catalogFile = fileURLToPath(import.meta.resolve('@lottiefiles/generative-icons/catalog.json'));
const libraryRoot = path.dirname(catalogFile), catalog = read(catalogFile);
const args = process.argv.slice(2);
function option(name) { const at = args.indexOf(name); if (at < 0) return; if (!args[at + 1] || args[at + 1].startsWith('--')) throw Error(`Missing value for ${name}`); return args.splice(at, 2)[1]; }
function output(value) { console.log(json(value)); }
function lock(root) {
  const file = inside(root, '.lottie-icons/lock.json');
  const value = fs.existsSync(file) ? read(file) : { schemaVersion: 1, libraryVersion: catalog.version, icons: {}, files: {} };
  if (value.schemaVersion !== 1) throw Error('Unsupported icon lock');
  return value;
}
function init(root) {
  const detected = inspectProject(root), exists = fs.existsSync(inside(root, 'lottie-icons.json'));
  const config = exists ? readConfig(root) : { schemaVersion: 1, ...detected, assets: 'public/lottie-icons', descriptors: `${detected.sourceDirectory === '.' ? '' : detected.sourceDirectory + '/'}lottie-icons`, publicPath: '/lottie-icons', defaults: { color: '#008c76', style: 'outline', weight: 2, motion: 'light' } };
  const files = {};
  if (!exists) files['lottie-icons.json'] = json(config);
  const skillRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), 'skill');
  for (const entry of fs.readdirSync(skillRoot, { recursive: true })) {
    const file = path.join(skillRoot, entry);
    if (fs.statSync(file).isFile()) files[`.agents/skills/lottie-icons/${entry}`] = fs.readFileSync(file);
  }
  output({ ...detected, changed: writeBatch(root, files), config: 'lottie-icons.json', next: 'lottie-icons search <meaning>, then lottie-icons add <id>' });
}
function add(root, ids) {
  if (!ids.length) throw Error('Provide at least one icon ID');
  const config = readConfig(root), current = lock(root), next = structuredClone(current), files = {};
  files[`${config.descriptors}/settings.mjs`] = `// Shared project defaults. Edit lottie-icons.json, then run add to update.\nexport const defaults = ${JSON.stringify(config.defaults, null, 2)};\n`;
  files[`${config.descriptors}/settings.d.mts`] = 'import type { PaintOptions } from "@lottiefiles/generative-icons-runtime";\nexport declare const defaults: PaintOptions;\n';
  for (const id of [...new Set(ids)]) {
    const icon = catalog.icons.find(i => i.id === id);
    if (!icon) throw Error(`Unknown icon: ${id}. Run lottie-icons search <meaning>.`);
    const bytes = fs.readFileSync(inside(libraryRoot, icon.asset.path));
    if (digest(bytes) !== icon.asset.sha256) throw Error(`Package asset hash mismatch: ${id}`);
    const source = `${config.descriptors}/${id}.mjs`, asset = `${config.assets}/${id}.lottie`;
    files[asset] = bytes;
    files[source] = `// Generated by lottie-icons. Review local edits before updating.\nexport const icon = ${JSON.stringify(icon, null, 2)};\nexport const src = ${JSON.stringify(config.publicPath.replace(/\/$/, '') + '/' + id + '.lottie')};\nexport default icon;\n`;
    files[`${config.descriptors}/${id}.d.mts`] = 'import type { IconDescriptor } from "@lottiefiles/generative-icons-runtime";\nexport declare const icon: IconDescriptor;\nexport declare const src: string;\nexport default icon;\n';
    next.icons[id] = { version: catalog.version, sha256: icon.asset.sha256, source, asset };
  }
  next.libraryVersion = catalog.version;
  for (const [name, bytes] of Object.entries(files)) next.files[name] = digest(bytes);
  files['.lottie-icons/lock.json'] = json(next);
  const expected = { ...current.files };
  const lockPath = inside(root, '.lottie-icons/lock.json');
  if (fs.existsSync(lockPath)) expected['.lottie-icons/lock.json'] = digest(fs.readFileSync(lockPath));
  output({ changed: writeBatch(root, files, expected), icons: ids, version: catalog.version });
}

function status(root) {
  const current = lock(root), result = [];
  for (const [file, sha] of Object.entries(current.files)) {
    const location = inside(root, file);
    result.push({ file, status: !fs.existsSync(location) ? 'missing' : digest(fs.readFileSync(location)) === sha ? 'unchanged' : 'modified' });
  }
  return result;
}

try {
  const root = fs.realpathSync(path.resolve(option('--cwd') || process.cwd()));
  const command = args.shift() || 'help';
  if (command === 'init') { if (args.length) throw Error('Usage: lottie-icons init [--cwd app]'); init(root); }
  else if (command === 'info') output({ ...inspectProject(root), libraryVersion: catalog.version, config: fs.existsSync(inside(root, 'lottie-icons.json')) ? readConfig(root) : null, files: status(root) });
  else if (command === 'search') {
    const query = args.join(' ').toLowerCase().trim(), words = query.split(/\s+/).filter(Boolean);
    output(catalog.icons.filter(icon => words.every(word => [icon.id, icon.label, icon.intent, icon.category, ...(icon.aliases || [])].join(' ').toLowerCase().includes(word))).map(({ id, label, category, stateful }) => ({ id, label, category, stateful })));
  }
  else if (command === 'add') add(root, args);
  else if (command === 'diff') output(status(root));
  else if (command === 'author') {
    const repo = option('--repo'), slug = args.shift();
    if (!repo || !slug || args.length) throw Error('Usage: lottie-icons author <set-slug> --repo <authoring-checkout>');
    const source = fs.realpathSync(path.resolve(repo));
    const doctor = spawnSync(process.execPath, [path.join(source, 'motion/src/doctor.mjs')], { stdio: 'inherit', cwd: source });
    if (doctor.status !== 0) throw Error('Authoring setup is incomplete. Fix doctor before scaffolding.');
    const created = spawnSync('python3', [path.join(source, 'scripts/icon-set.py'), 'new', slug], { stdio: 'inherit', cwd: source });
    if (created.status !== 0) throw Error('Authoring scaffold failed');
  }
  else if (command === 'help' || command === '--help') console.log('lottie-icons init | info | search <meaning> | add <id...> | diff\n  --cwd <app-folder> selects an app; no global configuration is changed.\nlottie-icons author <set-slug> --repo <authoring-checkout>\n  Native generation needs the external exporter and a source checkout.');
  else throw Error(`Unknown command: ${command}`);
} catch (error) { console.error(error.message); process.exitCode = 1; }
