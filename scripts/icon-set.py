"""Scaffold an editable set, then register it only after a verified native build."""
import argparse
import html
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SLUG = r'[a-z][a-z0-9]*(?:-[a-z0-9]+)*'


def read_json(file):
    return json.loads(file.read_text())


def scaffold(root, slug, name=None):
    if not re.fullmatch(SLUG, slug):
        raise ValueError('Use a lowercase set slug, such as landscaping. Do not include a path or number.')
    name = name or slug.replace('-', ' ').capitalize()
    if not name.strip() or '\n' in name or '\r' in name:
        raise ValueError('The display name must be a nonempty single line.')
    sets, pages = root / 'motion/icon-sets', root / 'prototype/icons'
    if list(sets.glob(f'[0-9][0-9]-{slug}')):
        raise ValueError(f'A source set named {slug} already exists.')
    used = {int(p.name[:2]) for p in sets.glob('[0-9][0-9]-*')}
    used.update(int(p.name) for p in pages.iterdir() if re.fullmatch(r'\d{2}', p.name))
    number = max(used, default=0) + 1
    if number > 99:
        raise ValueError('The current asset layout supports two-digit set numbers only.')
    set_id = f'{number:02}-{slug}'
    source, page = sets / set_id, pages / f'{number:02}'

    # Freeze the currently verified mixed-policy pipeline into each new set.
    # Existing versioned builders stay untouched, preserving their provenance.
    baseline = sets / '34-scheduling-time'
    builder = (baseline / 'build.mjs').read_text()
    verifier = (baseline / 'verify.mjs').read_text().replace('Stale scheduling-time builder', 'Stale set builder')
    renderer = (pages / '34/verify.html').read_text()
    renderer = renderer.replace('Scheduling & time tools', html.escape(name))
    renderer = renderer.replace('set:"34"', f'set:"{number:02}"')
    renderer = renderer.replace('location.port==="4191"', 'new URLSearchParams(location.search).get("save")==="1"')
    # The generic renderer keeps the complete frame/style/playback checks.
    # Asset-specific counter tests belong to the new drawing's own verifier.
    start = renderer.index("                  if (size >= 32 && size <= 48 && style !== 'duotone')")
    end = renderer.index('                  const b = pixels(buffer, size);', start)
    renderer = renderer[:start] + renderer[end:]
    config = {'id': set_id, 'name': name, 'category': name,
              'designReview': f'{set_id}/evidence', 'sharedSources': ['drawing.mjs', 'direction.mjs']}
    files = {
        'build.mjs': builder,
        'verify.mjs': verifier,
        'set-config.json': json.dumps(config, indent=2) + '\n',
        'definitions.mjs': '// Author named vector parts and custom Light/Strong motion here.\n// An empty set intentionally fails preflight; scaffolding is not a design.\nexport const icons = [];\n',
        'batches/.gitkeep': '',
        'package.py': 'from pathlib import Path\nimport subprocess,sys\nroot=Path(__file__).resolve().parent\nsubprocess.run([sys.executable,str(root.parent/"library/package-set.py"),str(root)],check=True)\n',
        'DOWNLOAD_README.txt': f'{name}\n\nNative dotLottie files with Light/Strong motion and Outline/Solid/Duotone styles. Editable source is under source/. Original work is MIT licensed; see LICENSE and THIRD_PARTY_NOTICES.md.\n',
        'evidence/design-review.md': '# Design and review record\n\nRecord meaning, reference IDs, named parts and pivots, Light/Strong timing, protected gaps, observed failures and corrections. Keep source checks, native rendering, agent visual review and user approval separate. Link final evidence to current package hashes.\n',
        'README.md': f'''# {name}

Author custom artwork in definitions.mjs using the family skill. No artwork is generated by the scaffold. Once the set is registered, replace this README with its icon list (see any registered set).

From the repository root:

```sh
npm run doctor
node motion/icon-sets/library/build-checked.mjs motion/icon-sets/{set_id}
node motion/icon-sets/{set_id}/verify.mjs
npm run icons:register -- {set_id}
npm run dev
```

Build before registration. Inspect the gallery at /icons/01/#category-{slug}.
For native frame checks, run the verification server described in docs/verification.md and open /icons/{number:02}/verify.html?save=1. Add drawing-specific contact and clearance checks; generic checks cannot establish visual quality.
''',
    }
    # Prepare both trees before moving either into place. Never replace a set.
    with tempfile.TemporaryDirectory(prefix='.new-set-', dir=sets) as temp:
        staged = Path(temp)
        for relative, content in files.items():
            p = staged / 'source' / relative
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content)
        (staged / 'page').mkdir()
        (staged / 'page/verify.html').write_text(renderer)
        if source.exists() or page.exists():
            raise ValueError('The selected set number was taken; retry with the current checkout.')
        (staged / 'source').rename(source)
        (staged / 'page').rename(page)
    return set_id


def register(root, set_id, run=subprocess.run):
    if not re.fullmatch(r'[0-9]{2}-' + SLUG, set_id):
        raise ValueError('Use a source set ID, such as 35-landscaping.')
    source = root / 'motion/icon-sets' / set_id
    config = read_json(source / 'set-config.json')
    if config['id'] != set_id:
        raise ValueError('The source directory and configured set ID disagree.')
    relative = f'{set_id[:2]}/assets/set.json'
    manifest = root / 'prototype/icons' / relative
    if not manifest.is_file():
        raise ValueError('Build the complete set before registration; its asset manifest is missing.')
    data = read_json(manifest)
    if data.get('id') != set_id or not data.get('icons'):
        raise ValueError('The built manifest must match this set and contain icons.')
    catalog_file = root / 'prototype/icons/catalog.json'
    before = catalog_file.read_bytes()
    catalog = json.loads(before)
    # Preflight detects duplicate public IDs; the native verifier rejects stale
    # source, package hashes, topology, state boundaries and exported transforms.
    for script, args in [
        (root / 'motion/icon-sets/library/preflight.mjs', [source]),
        (source / 'verify.mjs', []),
    ]:
        result = run(['node', str(script), *map(str, args)], cwd=root,
                     capture_output=True, text=True)
        if result.returncode:
            raise ValueError(f'Registration stopped: {script.name} failed.\n{result.stderr or result.stdout}')
    category = set_id[3:]
    current = next((c for c in catalog['categories'] if c['id'] == category), None)
    if current and relative not in current['sets']:
        raise ValueError(f'Category {category} already belongs to another set; edit that category deliberately.')
    if relative not in catalog['sets']:
        catalog['sets'].append(relative)
    if not current:
        catalog['categories'].append({'id': category, 'label': config['name'], 'sets': [relative]})
    updated = (json.dumps(catalog, indent=2) + '\n').encode()
    if updated != before:
        with tempfile.NamedTemporaryFile(dir=catalog_file.parent, prefix='.catalog-', delete=False) as temp:
            temp.write(updated)
            pending = Path(temp.name)
        try:
            if catalog_file.read_bytes() != before:
                raise ValueError('The catalog changed during verification. Retry registration.')
            pending.replace(catalog_file)
        finally:
            pending.unlink(missing_ok=True)
    return relative


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    new = commands.add_parser('new')
    new.add_argument('slug')
    new.add_argument('--name')
    add = commands.add_parser('register')
    add.add_argument('set_id')
    args = parser.parse_args()
    try:
        if args.command == 'new':
            set_id = scaffold(ROOT, args.slug, args.name)
            print(f'Created motion/icon-sets/{set_id}. Author definitions.mjs, then build and verify.\n'
                  f'Register after a successful build: npm run icons:register -- {set_id}\n'
                  'The catalog is unchanged. Scaffolding does not generate or approve artwork.')
        else:
            register(ROOT, args.set_id)
            print('Registered the verified build. Run npm run dev and inspect the gallery. '
                  'Registration is not visual approval. Repackage after final review to include the updated catalog and evidence.')
    except (ValueError, OSError, KeyError) as error:
        parser.exit(1, f'{error}\n')


if __name__ == '__main__':
    main()
