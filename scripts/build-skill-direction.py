"""Copy the family's direction into the CLI's agent skill, so local icons follow the same rules as the library.

The sources stay canonical. The copies in crates/generative-icons/assets/skill/references/ are
generated by `npm run docs:build`, compiled into the binary and installed by `generative-icons init`;
check-docs.py fails when one is stale. Edit the source, never the copy.
"""
from pathlib import Path
import re,sys
root=Path(__file__).resolve().parents[1]
out=root/'crates/generative-icons/assets/skill/references'
workflow='.agents/skills/animated-icon-workflow'
base='https://github.com/LottieFiles/generative-icons/blob/main/'
LIBRARY_NOTE=('> These are the Generative Icons library\'s own rules, shipped with the CLI so the icons you make match the family. '
 'Where they name repository files, the gallery or `library` commands, use this skill\'s loop instead: '
 '`context`, `create`, `check`, `draft`, `build` and `preview` ([SKILL.md](../SKILL.md)).')
# (copy, title for an excerpt or None to keep the source's own, source, headings to keep or None for all, note)
COPIES=[
 ('motion-principles.md',None,'docs/motion-principles.md',None,None),
 ('motion-system.md',None,'MOTION.md',None,None),
 ('design-principles.md',None,'docs/design-principles.md',None,None),
 ('craft.md','# Drawing and motion craft',f'{workflow}/SKILL.md',
  ['## 2. Draw the complete object','## 3. Direct the motion before keyframing','### Continuous indicators'],LIBRARY_NOTE),
 ('polish-review.md',None,f'{workflow}/references/polish-review.md',None,LIBRARY_NOTE),
]
SIBLINGS={source:copy for copy,_,source,_,_ in COPIES}
# Links into this repository under its current or earlier name.
REPO_URL=re.compile(r'https://github\.com/LottieFiles/(?:generative-icons|gen-animated-icons)/blob/main/(.+)')

def excerpt(text,headings):
 """The given `##`/`###` sections, each up to the next heading of the same or a higher level."""
 lines=text.splitlines();parts=[]
 for heading in headings:
  level=len(heading.split(' ')[0])
  try:start=lines.index(heading)
  except ValueError:sys.exit(f'build-skill-direction: missing heading {heading!r}')
  end=next((i for i in range(start+1,len(lines)) if re.match(r'#{1,%d} '%level,lines[i])),len(lines))
  parts.append('\n'.join(lines[start:end]).strip())
 return '\n\n'.join(parts)

def links(text,source):
 """Relative links to another copied document point at its copy; the rest point at the repository."""
 def replace(m):
  label,target=m.groups()
  if target.startswith(('mailto:','#')):return m.group(0)
  location,_,fragment=target.partition('#')
  if (repo:=REPO_URL.match(location)):rel=repo.group(1)
  elif location.startswith(('http:','https:')):return m.group(0)
  else:rel=(root/source).parent.joinpath(location).resolve().relative_to(root).as_posix()
  url=SIBLINGS.get(rel) or base+rel
  return f'[{label}]({url}{"#"+fragment if fragment else ""})'
 return re.sub(r'\[([^\]]+)\]\(([^)]+)\)',replace,text)

def render(copy,title,source,headings,note):
 text=(root/source).read_text()
 body=excerpt(text,headings) if headings else text.strip()
 head=[f'<!-- Generated from {source} by `npm run docs:build`. Edit the source, not this copy. -->']
 if title:head+=[title,*([note] if note else [])]
 elif note:
  # The note goes right after the source's own H1.
  first,_,rest=body.partition('\n')
  body=f'{first}\n\n{note}\n{rest}' if first.startswith('# ') else f'{note}\n\n{body}'
 return '\n\n'.join([*head,links(body,source)])+'\n'

def outputs():
 return {out/copy:render(copy,title,source,headings,note) for copy,title,source,headings,note in COPIES}

if __name__=='__main__':
 for path,text in outputs().items():
  path.write_text(text)
 print(f'Wrote {len(COPIES)} direction references to {out.relative_to(root)}')
